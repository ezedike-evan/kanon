/**
 * Bundles the chart runtime for the native WebView.
 *
 * The runtime (`src/components/chart/runtime`) is ordinary TypeScript that
 * imports lightweight-charts. On web it is imported like any module. A
 * react-native-webview cannot import anything, so this bundles the WebView
 * entry, the runtime and lightweight-charts into one minified IIFE and writes
 * it as a string constant next to the native engine. That is why the native
 * chart needs no network and no CDN, and why `Function.toString()` (which
 * Hermes does not support) is never involved.
 *
 *   node scripts/build-chart-runtime.mjs          write the generated file
 *   node scripts/build-chart-runtime.mjs --check  exit 1 if it is stale
 *
 * `src/lib/chart-runtime-bundle.test.ts` runs the check, so a runtime edit
 * that forgets to regenerate fails the suite instead of shipping a stale chart.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'src/components/chart/runtime/webview-entry.ts');
export const outFile = path.join(root, 'src/components/chart/runtime-bundle.generated.ts');

export async function buildRuntimeFile() {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2019',
    minify: true,
    legalComments: 'none',
    logLevel: 'silent',
  });
  const code = result.outputFiles[0].text;
  return (
    '// GENERATED by scripts/build-chart-runtime.mjs from src/components/chart/runtime.\n' +
    '// Do not edit. Run `pnpm --filter @kanon/ui build:chart` after changing the runtime.\n' +
    `export const CHART_RUNTIME_BUNDLE = ${JSON.stringify(code)};\n`
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = await buildRuntimeFile();
  if (process.argv.includes('--check')) {
    const current = await readFile(outFile, 'utf8').catch(() => '');
    if (current !== next) {
      console.error('runtime-bundle.generated.ts is stale. Run: pnpm --filter @kanon/ui build:chart');
      process.exit(1);
    }
    console.log('runtime bundle is up to date');
  } else {
    await writeFile(outFile, next);
    console.log(`wrote ${path.relative(root, outFile)} (${(next.length / 1024).toFixed(0)} KB)`);
  }
}
